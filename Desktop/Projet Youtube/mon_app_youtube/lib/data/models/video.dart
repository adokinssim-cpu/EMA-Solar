class Video {
  final String id;
  final String title;
  final String channelName;
  final String views;
  final String thumbnailUrl;
  final String duration;

  Video({
    required this.id,
    required this.title,
    required this.channelName,
    required this.views,
    required this.thumbnailUrl,
    required this.duration,
  });
}
